"""Recover files from incomplete TFTP receive replicas.

A receiver interrupted by packet loss, a restart, or a shutdown leaves a
partial sequence of TFTP data blocks behind.  Several such receive backups of
the same transfer can be combined, but only when the combination satisfies the
transfer's version declaration (block size, file size, version tag) and every
segment digest generated by the device.  A digest range is a byte range and
may span more than one TFTP block.

Recovery is global, not per block.  Every block choice is evaluated as part of
a complete candidate file, so two replicas that are each wrong in a different
block cannot be resolved by a block-by-block majority vote.

When more than one complete file satisfies the declaration, only the byte
ranges that are identical in every legal completion are delivered.  Remaining
ranges are reported as pending (``pending`` / reason ``ambiguous``) so they
can be requested again later.

TFTP end-of-file rules are part of the declaration:

* block numbers start at 1;
* every non-final data block has exactly the negotiated block size;
* a file whose size is an exact multiple of the block size ends with an
  additional empty block;
* an empty file is a single empty block;
* the final short block and the empty block are attributed to a replica.
"""

