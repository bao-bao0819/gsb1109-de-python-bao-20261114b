class RecoveryError(TftpException):
    """Base class for errors raised during replica recovery."""


class RecoveryDeclarationError(RecoveryError, ValueError):
    """The version declaration or a digest is malformed or contradictory."""


class IncompleteRecoveryError(RecoveryError):
    """A complete file could not be recovered."""

    def __init__(self, result):
        self.result = result
        super().__init__(
            "incomplete recovery for %s: %d pending range(s)"
            % (result.name, len(result.pending_ranges))
        )


class RecoveryAmbiguityError(IncompleteRecoveryError):
    """More than one legal completion exists."""


class RecoveryLimitError(RecoveryError):
    """The candidate search exceeded its configured limit."""


def _normalize_algorithm(algorithm):
    if algorithm is None:
        return "sha256"
    name = str(algorithm).strip().lower()
    aliases = {
        "sha-1": "sha1",
        "sha-224": "sha224",
        "sha-256": "sha256",
        "sha-384": "sha384",
        "sha-512": "sha512",
    }
    name = aliases.get(name, name)
    try:
        hashlib.new(name)
    except (ValueError, TypeError) as err:
        raise RecoveryDeclarationError(
            "unsupported digest algorithm %r" % (algorithm,)
        ) from err
    return name


def _decode_digest(value):
    """Decode a digest provided as bytes, hex, or base64."""
    if isinstance(value, (bytes, bytearray, memoryview)):
        return bytes(value)
    if not isinstance(value, str):
        raise RecoveryDeclarationError("digest must be bytes or text")
    text = value.strip()
    if ":" in text:
        prefix, rest = text.split(":", 1)
        if prefix.lower().replace("-", "") in (
            "sha1", "sha224", "sha256", "sha384", "sha512",
            "md5", "blake2b", "blake2s",
        ):
            text = rest.strip()
    text = text.replace(" ", "")
    try:
        return bytes.fromhex(text)
    except ValueError:
        pass
    try:
        return base64.b64decode(text, validate=True)
    except (binascii.Error, ValueError) as err:
        raise RecoveryDeclarationError("digest is neither hex nor base64") from err


def _decode_block(value):
    """Decode block data from bytes or a JSON-friendly encoding.

    A plain string is treated as UTF-8 text.  Binary data must be tagged with
    ``hex:`` or ``base64:`` so that a text value cannot be misread as binary.
    """
    if isinstance(value, (bytes, bytearray, memoryview)):
        return bytes(value)
    if isinstance(value, str):
        text = value
        if text.startswith("hex:"):
            try:
                return bytes.fromhex(text[4:])
            except ValueError as err:
                raise RecoveryDeclarationError("invalid hex block data") from err
        if text.startswith("base64:"):
            try:
                return base64.b64decode(text[7:], validate=True)
            except (binascii.Error, ValueError) as err:
                raise RecoveryDeclarationError(
                    "invalid base64 block data"
                ) from err
        return text.encode("utf-8")
    raise RecoveryDeclarationError("block data must be bytes or text")


def _normalize_blocks(blocks):
    """Accept a mapping, an iterable of pairs, or an iterable of blocks."""
    if blocks is None:
        return {}
    if isinstance(blocks, Mapping):
        items = list(blocks.items())
    else:
        items = list(blocks)
    result = {}
    for item in items:
        if isinstance(item, (bytes, bytearray, memoryview)):
            number, data = len(result) + 1, item
        elif isinstance(item, Mapping):
            number = item.get("number", item.get("block"))
            data = item.get("data", item.get("bytes"))
        else:
            try:
                number, data = item
            except (TypeError, ValueError) as err:
                raise RecoveryDeclarationError("invalid block entry") from err
        if isinstance(number, str):
            try:
                number = int(number, 0)
            except ValueError as err:
                raise RecoveryDeclarationError(
                    "block number must be an integer"
                ) from err
        if not isinstance(number, int):
            raise RecoveryDeclarationError("block number must be an integer")
        if number < 1:
            raise RecoveryDeclarationError("TFTP block numbers start at 1")
        if number in result:
            raise RecoveryDeclarationError("duplicate block %d" % number)
        result[number] = _decode_block(data)
    return result


@dataclass(frozen=True)
class Replica:
    """One incomplete receive backup of a file.

    ``blocks`` maps TFTP block numbers to the bytes received for that block.
    ``blocksize`` and ``declared_size`` are optional statements made by the
    receiver (for example from the OACK/tsize option).  ``version`` is the file
    version the replica claims to hold; replicas whose version disagrees with
    the target declaration are not used.
    """

    name: str
    blocks: Mapping[int, bytes] = field(default_factory=dict)
    blocksize: Optional[int] = None
    declared_size: Optional[int] = None
    version: Optional[str] = None
    source: Optional[str] = None

    def __post_init__(self):
        object.__setattr__(self, "blocks", _normalize_blocks(self.blocks))
        if not self.name:
            raise RecoveryDeclarationError("replica name is required")
        if self.blocksize is not None:
            if not isinstance(self.blocksize, int):
                raise RecoveryDeclarationError("blocksize must be an integer")
            if not MIN_BLKSIZE <= self.blocksize <= MAX_BLKSIZE:
                raise RecoveryDeclarationError(
                    "invalid blocksize %d" % self.blocksize
                )
        if self.declared_size is not None:
            if not isinstance(self.declared_size, int) or self.declared_size < 0:
                raise RecoveryDeclarationError(
                    "declared size must be a non-negative integer"
                )

    @classmethod
    def from_mapping(cls, value, name=None, index=None, **kwargs):
        if isinstance(value, Replica):
            return value
        if not isinstance(value, Mapping):
            raise RecoveryDeclarationError("replica must be a mapping")
        data = dict(value)
        if "block_size" in data and "blocksize" not in data:
            data["blocksize"] = data.pop("block_size")
        if "size" in data and "declared_size" not in data:
            data["declared_size"] = data.pop("size")
        if name is not None:
            data.setdefault("name", name)
        if data.get("name") is None:
            data["name"] = "replica-%d" % (
                (index + 1) if index is not None else 1
            )
        data.update(kwargs)
        return cls(**data)

    @property
    def block_numbers(self):
        return tuple(sorted(self.blocks))

    @property
    def size(self):
        """Bytes present in the replica, in block order."""
        return sum(len(self.blocks[n]) for n in sorted(self.blocks))

    def block(self, number):
        return self.blocks.get(number)

    def as_dict(self):
        return {
            "name": self.name,
            "blocks": {
                str(number): base64.b64encode(data).decode("ascii")
                for number, data in sorted(self.blocks.items())
            },
            "blocksize": self.blocksize,
            "size": self.declared_size,
            "version": self.version,
            "source": self.source,
        }


ReceivedReplica = Replica
BackupReplica = Replica


@dataclass(frozen=True)
class SegmentDigest:
    """A digest over a half-open byte range of the recovered file.

    ``end`` may be ``None`` to mean end-of-file.  The range may cover any
    number of TFTP blocks and may begin or end inside a block.
    """

    start: int
    end: Optional[int]
    digest: Any
    algorithm: str = "sha256"

    def __post_init__(self):
        if not isinstance(self.start, int) or self.start < 0:
            raise RecoveryDeclarationError("digest start must be >= 0")
        if self.end is not None:
            if not isinstance(self.end, int):
                raise RecoveryDeclarationError("digest end must be an integer")
            if self.end < self.start:
                raise RecoveryDeclarationError("digest end precedes its start")
        algorithm = _normalize_algorithm(self.algorithm)
        value = _decode_digest(self.digest)
        expected = hashlib.new(algorithm).digest_size
        if len(value) != expected:
            raise RecoveryDeclarationError(
                "%s digest must be %d bytes, got %d"
                % (algorithm, expected, len(value))
            )
        object.__setattr__(self, "algorithm", algorithm)
        object.__setattr__(self, "digest", value)

    @classmethod
    def from_value(cls, value, algorithm=None):
        if isinstance(value, SegmentDigest):
            return value
        if isinstance(value, Mapping):
            data = dict(value)
            if "length" in data and "end" not in data:
                data["end"] = data["start"] + data.pop("length")
            if "hash" in data and "digest" not in data:
                data["digest"] = data.pop("hash")
            if "range" in data and "start" not in data:
                start, end = data.pop("range")
                data["start"] = start
                data["end"] = end
            if "algo" in data and "algorithm" not in data:
                data["algorithm"] = data.pop("algo")
            if algorithm is not None:
                data.setdefault("algorithm", algorithm)
            return cls(**data)
        if isinstance(value, (tuple, list)):
            if len(value) == 3:
                start, end, digest = value
                return cls(start, end, digest, algorithm or "sha256")
            if len(value) == 4:
                start, end, digest, algo = value
                return cls(start, end, digest, algo)
        raise RecoveryDeclarationError("invalid digest declaration")

    @property
    def length(self):
        return None if self.end is None else self.end - self.start

    def matches(self, data):
        return hashlib.new(self.algorithm, data).digest() == self.digest

    def as_dict(self):
        return {
            "start": self.start,
            "end": self.end,
            "algorithm": self.algorithm,
            "digest": self.digest.hex(),
        }


Digest = SegmentDigest
SegmentSummary = SegmentDigest


@dataclass(frozen=True)
class VersionDeclaration:
    """What the device says the complete file must look like.

    ``size`` is the file size (TFTP ``tsize``), ``blocksize`` the negotiated
    block size, ``version`` an optional version tag, and ``digests`` the
    device-generated segment summaries.
    """

    size: Optional[int] = None
    blocksize: Optional[int] = None
    version: Optional[str] = None
    digests: Tuple[SegmentDigest, ...] = ()
    algorithm: str = "sha256"
    max_candidates: int = 10000
    max_nodes: int = 500000

    def __post_init__(self):
        if self.size is not None:
            if not isinstance(self.size, int) or self.size < 0:
                raise RecoveryDeclarationError(
                    "size must be a non-negative integer"
                )
        if self.blocksize is not None:
            if not isinstance(self.blocksize, int):
                raise RecoveryDeclarationError("blocksize must be an integer")
            if not MIN_BLKSIZE <= self.blocksize <= MAX_BLKSIZE:
                raise RecoveryDeclarationError(
                    "invalid blocksize %d" % self.blocksize
                )
        if not isinstance(self.max_candidates, int) or self.max_candidates < 1:
            raise RecoveryDeclarationError("max_candidates must be positive")
        if not isinstance(self.max_nodes, int) or self.max_nodes < 1:
            raise RecoveryDeclarationError("max_nodes must be positive")
        algorithm = _normalize_algorithm(self.algorithm)
        digests = tuple(
            SegmentDigest.from_value(item, algorithm) for item in self.digests
        )
        object.__setattr__(self, "algorithm", algorithm)
        object.__setattr__(self, "digests", digests)

    @classmethod
    def from_mapping(cls, value, **kwargs):
        if isinstance(value, VersionDeclaration):
            return value
        if not isinstance(value, Mapping):
            raise RecoveryDeclarationError(
                "version declaration must be a mapping"
            )
        data = dict(value)
        for key in ("digest", "segments", "summaries", "segment_digests"):
            if key in data:
                data.setdefault("digests", data.pop(key))
        if "block_size" in data and "blocksize" not in data:
            data["blocksize"] = data.pop("block_size")
        if "tsize" in data and "size" not in data:
            data["size"] = data.pop("tsize")
        if "tag" in data and "version" not in data:
            data["version"] = data.pop("tag")
        data.update(kwargs)
        return cls(**data)

    @property
    def segments(self):
        return self.digests

    def as_dict(self):
        return {
            "size": self.size,
            "blocksize": self.blocksize,
            "version": self.version,
            "digests": [digest.as_dict() for digest in self.digests],
        }


