@dataclass
class FileRecoveryResult:
    """Outcome of recovering one file.

    When ``complete`` is true, ``data`` is the whole file.  When it is false,
    ``data`` is a representative legal completion (if one exists) and only
    the ranges marked ``recovered`` may be delivered; everything else is
    pending.
    """

    name: str
    size: Optional[int]
    blocksize: Optional[int]
    version: Optional[str]
    complete: bool
    empty: bool
    data: Optional[bytes]
    ranges: Tuple[RecoveredRange, ...] = ()
    blocks: Tuple[BlockSource, ...] = ()
    segments: Tuple[SegmentReadback, ...] = ()
    legal_completions: int = 0
    reason: Optional[str] = None
    eof_marker_missing: bool = False
    size_inferred: bool = False
    algorithms: Tuple[str, ...] = ()

    @property
    def pending_ranges(self):
        return tuple(item for item in self.ranges if item.status == PENDING)

    @property
    def recovered_ranges(self):
        return tuple(item for item in self.ranges if item.status == RECOVERED)

    @property
    def pending(self):
        return not self.complete

    @property
    def empty_sources(self):
        if not self.empty:
            return ()
        for block in self.blocks:
            if block.is_empty:
                return block.sources
        return ()

    @property
    def last_block(self):
        return self.blocks[-1] if self.blocks else None

    @property
    def eof_source(self):
        """Replica(s) that supplied the short final block or empty block."""
        block = self.last_block
        if block is not None and (block.is_short or block.is_empty):
            return block.sources
        return ()

    def sources_for(self, start, end):
        """Return replicas that can read back the given byte range."""
        for item in self.ranges:
            if item.start <= start and end <= item.end and item.recovered:
                return item.sources
        return ()

    def iter_delivered(self):
        """Yield ``(start, data)`` for deliverable ranges in order."""
        if self.data is None:
            return
        if self.complete:
            yield 0, self.data
            return
        for item in self.recovered_ranges:
            if item.length:
                yield item.start, self.data[item.start:item.end]

    def to_bytes(self):
        """Return the complete file, or raise if recovery is incomplete."""
        if not self.complete or self.data is None:
            raise IncompleteRecoveryError(self)
        return self.data

    def write(self, path):
        """Write a complete file; an empty file is written with zero bytes."""
        data = self.to_bytes()
        directory = os.path.dirname(os.path.abspath(path))
        if directory:
            os.makedirs(directory, exist_ok=True)
        with open(path, "wb") as handle:
            handle.write(data)
        return path

    save = write

    def as_dict(self):
        return {
            "name": self.name,
            "size": self.size,
            "blocksize": self.blocksize,
            "version": self.version,
            "complete": self.complete,
            "empty": self.empty,
            "empty_sources": list(self.empty_sources),
            "eof_source": list(self.eof_source),
            "legal_completions": self.legal_completions,
            "reason": self.reason,
            "eof_marker_missing": self.eof_marker_missing,
            "size_inferred": self.size_inferred,
            "algorithms": list(self.algorithms),
            "ranges": [item.as_dict() for item in self.ranges],
            "pending_ranges": [item.as_dict() for item in self.pending_ranges],
            "blocks": [item.as_dict() for item in self.blocks],
            "segments": [item.as_dict() for item in self.segments],
        }


FileRecovery = FileRecoveryResult


@dataclass(frozen=True)
class FileReplicas:
    """A set of receive replicas and the declaration for one file."""

    name: str
    replicas: Tuple[Replica, ...]
    declaration: VersionDeclaration = field(default_factory=VersionDeclaration)

    def __post_init__(self):
        if not self.name:
            raise RecoveryDeclarationError("file name is required")
        replicas = tuple(
            Replica.from_mapping(item, index=index)
            for index, item in enumerate(self.replicas)
        )
        object.__setattr__(self, "replicas", replicas)
        if not isinstance(self.declaration, VersionDeclaration):
            object.__setattr__(
                self,
                "declaration",
                VersionDeclaration.from_mapping(self.declaration),
            )

    @classmethod
    def from_mapping(cls, value, **kwargs):
        if isinstance(value, FileReplicas):
            return value
        if not isinstance(value, Mapping):
            raise RecoveryDeclarationError("file declaration must be a mapping")
        data = dict(value)
        if "filename" in data and "name" not in data:
            data["name"] = data.pop("filename")
        declaration = data.pop("declaration", None)
        if declaration is None:
            keys = {}
            for key in (
                "size", "tsize", "blocksize", "block_size", "version", "tag",
                "digests", "digest", "segments", "summaries",
                "segment_digests", "algorithm", "max_candidates", "max_nodes",
            ):
                if key in data:
                    keys[key] = data.pop(key)
            declaration = keys
        data["declaration"] = VersionDeclaration.from_mapping(declaration)
        data.update(kwargs)
        return cls(**data)


RecoverySpec = FileReplicas


@dataclass
class BatchRecoveryResult:
    """Outcome of recovering a batch of files."""

    files: Tuple[FileRecoveryResult, ...]

    @property
    def complete(self):
        return all(item.complete for item in self.files)

    @property
    def pending_files(self):
        return tuple(item for item in self.files if not item.complete)

    @property
    def complete_files(self):
        return tuple(item for item in self.files if item.complete)

    @property
    def confirmed_empty_files(self):
        return tuple(item for item in self.files if item.empty and item.complete)

    def __iter__(self):
        return iter(self.files)

    def __len__(self):
        return len(self.files)

    def __getitem__(self, key):
        if isinstance(key, int):
            return self.files[key]
        for item in self.files:
            if item.name == key:
                return item
        raise KeyError(key)

    def for_file(self, name):
        return self[name]

    def write_all(self, directory, skip_incomplete=False):
        """Write every recoverable file, returning name-to-path mappings."""
        os.makedirs(directory, exist_ok=True)
        written = {}
        for item in self.files:
            if not item.complete:
                if skip_incomplete:
                    continue
                raise IncompleteRecoveryError(item)
            written[item.name] = item.write(os.path.join(directory, item.name))
        return written

    def as_dict(self):
        return {
            "complete": self.complete,
            "files": [item.as_dict() for item in self.files],
            "pending_files": [item.name for item in self.pending_files],
            "confirmed_empty_files": [
                item.name for item in self.confirmed_empty_files
            ],
        }


RecoveryResult = BatchRecoveryResult


def _block_lengths(size, blocksize):
    if size == 0:
        return [0]
    full, remainder = divmod(size, blocksize)
    if remainder == 0:
        return [blocksize] * full + [0]
    return [blocksize] * full + [remainder]


def _infer_blocksize(replicas, declaration):
    if declaration.blocksize is not None:
        return declaration.blocksize
    claimed = {item.blocksize for item in replicas if item.blocksize is not None}
    if len(claimed) > 1:
        raise RecoveryDeclarationError(
            "replicas disagree about block size: %s"
            % ", ".join(str(value) for value in sorted(claimed))
        )
    if claimed:
        return claimed.pop()
    lengths = Counter()
    for replica in replicas:
        numbers = replica.block_numbers
        for number in numbers[:-1]:
            lengths[len(replica.blocks[number])] += 1
    if lengths:
        return lengths.most_common(1)[0][0]
    maximum = max(
        (len(data) for replica in replicas for data in replica.blocks.values()),
        default=0,
    )
    if maximum:
        return max(min(maximum, MAX_BLKSIZE), MIN_BLKSIZE)
    return DEF_BLKSIZE


def _eof_layouts(replicas, blocksize):
    """Infer possible file sizes from short final blocks only.

    A short block is a trustworthy EOF marker only when no replica has any
    later block.  A transfer that ends on a block boundary must carry the
    additional empty block; without it the end is unknown, so no layout is
    inferred.
    """
    highest = max(
        (number for replica in replicas for number in replica.block_numbers),
        default=0,
    )
    layouts = []
    for replica in replicas:
        for number, data in sorted(replica.blocks.items()):
            if number != highest:
                continue
            if len(data) < blocksize:
                size = (number - 1) * blocksize + len(data)
                if (size, False) not in layouts:
                    layouts.append((size, False))
    return layouts


def _resolve_digests(declaration, size):
    resolved = []
    seen = set()
    for digest in declaration.digests:
        end = size if digest.end is None else digest.end
        if end > size:
            raise RecoveryDeclarationError(
                "digest range [%d, %d) exceeds file size %d"
                % (digest.start, end, size)
            )
        key = (digest.start, end, digest.algorithm, digest.digest)
        if key in seen:
            continue
        seen.add(key)
        resolved.append((digest.start, end, digest))
    return resolved


def _eligible_replicas(replicas, declaration):
    selected = []
    for replica in replicas:
        if (
            declaration.version is not None
            and replica.version is not None
            and str(replica.version) != str(declaration.version)
        ):
            continue
        if (
            declaration.size is not None
            and replica.declared_size is not None
            and replica.declared_size != declaration.size
        ):
            continue
        selected.append(replica)
    return selected


class _CandidateSearch:
    """Enumerate complete block assignments that satisfy every digest."""

    def __init__(self, replicas, layout, blocksize, resolved, limit, max_nodes):
        self.replicas = replicas
        self.layout = layout
        self.blocksize = blocksize
        self.resolved = resolved
        self.limit = limit
        self.max_nodes = max_nodes
        self.nodes = 0
        self.truncated = False
        self.contents = []
        self.options = []
        self.missing = []

    def _options_for(self, number, expected):
        options = {}
        for replica in self.replicas:
            data = replica.blocks.get(number)
            if data is None or len(data) != expected:
                continue
            options.setdefault(data, []).append(replica.name)
        return list(options)

    def build(self):
        for number, expected in enumerate(self.layout, start=1):
            options = self._options_for(number, expected)
            if not options:
                self.missing.append(number)
                return False
            self.options.append(options)
        return True

    def _constraints(self):
        """Map an ending block number to digest specs that end there."""
        constraints = {}
        for start, end, digest in self.resolved:
            if end == start:
                continue
            first = start // self.blocksize + 1
            last = (end - 1) // self.blocksize + 1
            if last > len(self.layout):
                continue
            constraints.setdefault(last, []).append((first, start, end, digest))
        return constraints

    def run(self):
        """Enumerate satisfying assignments with an explicit stack.

        An explicit stack keeps deep or long transfers from exhausting the
        interpreter recursion limit while preserving the same pruning.  The
        stack holds ``(index, position, chosen)`` where ``chosen`` is the
        immutable prefix of blocks selected so far.
        """
        if not self.build():
            return []
        constraints = self._constraints()
        total = len(self.options)
        contents = []

        def consistent(chosen, index):
            """Check digests that end at the block just appended."""
            for first, start, end, digest in constraints.get(index + 1, ()):
                left = (first - 1) * self.blocksize
                window = b"".join(chosen[first - 1:index + 1])
                offset = start - left
                right = end - left
                if offset < 0 or right > len(window):
                    return False
                if not digest.matches(window[offset:right]):
                    return False
            return True

        stack = [(0, 0, ())]
        while stack:
            index, position, chosen = stack.pop()
            if position == 0:
                self.nodes += 1
                if self.nodes > self.max_nodes:
                    self.truncated = True
                    break
            if len(contents) >= self.limit:
                self.truncated = True
                break
            if index == total:
                contents.append(b"".join(chosen))
                continue
            options = self.options[index]
            if position >= len(options):
                continue
            stack.append((index, position + 1, chosen))
            candidate = chosen + (options[position],)
            if consistent(candidate, index):
                stack.append((index + 1, 0, candidate))
        self.contents = contents
        return contents


def _common_ranges(contents):
    """Return half-open ranges that are byte-identical in all candidates."""
    if not contents:
        return []
    length = len(contents[0])
    if any(len(item) != length for item in contents):
        return []
    ranges = []
    start = None
    for index in range(length):
        value = contents[0][index]
        same = all(item[index] == value for item in contents[1:])
        if same and start is None:
            start = index
        elif not same and start is not None:
            ranges.append((start, index))
            start = None
    if start is not None:
        ranges.append((start, length))
    return ranges


def _range_sources(replica, data, blocksize, start, end):
    """Check whether one replica can provide the whole range."""
    if end == start:
        return False
    numbers = range(start // blocksize + 1, (end - 1) // blocksize + 2)
    for number in numbers:
        block_start = (number - 1) * blocksize
        block = replica.blocks.get(number)
        if block is None:
            return False
        left = max(start, block_start) - block_start
        right = min(end, block_start + len(block)) - block_start
        if right < left:
            return False
        if block[left:right] != data[
            block_start + left:block_start + right
        ]:
            return False
    return True


def _sources_and_blocks(replicas, data, blocksize, start, end):
    if end == start:
        return (), ()
    sources = tuple(
        replica.name
        for replica in replicas
        if _range_sources(replica, data, blocksize, start, end)
    )
    first = start // blocksize + 1
    last = (end - 1) // blocksize + 1
    return sources, tuple(range(first, last + 1))


def _block_sources(replica, number, data, blocksize):
    """Whether a replica holds exactly this block, including empty blocks."""
    if number not in replica.blocks:
        return False
    block = replica.blocks[number]
    start = (number - 1) * blocksize
    return block == data[start:start + len(block)]


def _group_ranges(replicas, data, blocksize, blocks):
    """Group contiguous blocks that share the same readback source set."""
    ranges = []
    current = None
    for block in blocks:
        if block.length == 0:
            continue
        if current is not None:
            same_sources = current[2] == block.sources
            adjacent = current[1] == block.start
            if same_sources and adjacent:
                current = (current[0], block.end, current[2], current[3] + (block.block,))
                continue
            ranges.append(current)
        current = (block.start, block.end, block.sources, (block.block,))
    if current is not None:
        ranges.append(current)
    return tuple(
        RecoveredRange(start, end, RECOVERED, sources, blocks)
        for start, end, sources, blocks in ranges
    )


def _pending_whole(size, reason):
    return (RecoveredRange(0, size or 0, PENDING, (), (), reason),)


def _segments_result(declaration, size, blocksize, candidates, replicas):
    segments = []
    for digest in declaration.digests:
        end = size if digest.end is None else digest.end
        if end is None or end > size:
            segments.append(
                SegmentReadback(digest.start, end, False, (), True)
            )
            continue
        values = {item[digest.start:end] for item in candidates}
        if len(values) != 1:
            segments.append(
                SegmentReadback(digest.start, end, False, (), True)
            )
            continue
        data = candidates[0]
        sources, blocks = _sources_and_blocks(
            replicas, data, blocksize, digest.start, end
        )
        readback = ()
        if not sources and end > digest.start:
            readback = _segment_readback(
                replicas, data, blocksize, digest.start, end
            )
        segments.append(
            SegmentReadback(
                digest.start, end, True, sources, False, blocks, readback
            )
        )
    return tuple(segments)


def _segment_readback(replicas, data, blocksize, start, end):
    """Split a segment into contiguous runs by their usable replica set."""
    pieces = []
    current = None
    for number in range(start // blocksize + 1, (end - 1) // blocksize + 2):
        block_start = (number - 1) * blocksize
        left = max(start, block_start)
        right = min(end, block_start + blocksize)
        if right <= left:
            continue
        sources = tuple(
            replica.name
            for replica in replicas
            if _range_sources(replica, data, blocksize, left, right)
        )
        if current is not None:
            adjacent = current[1] == left
            shared = current[2] == sources
            if adjacent and shared:
                current = (
                    current[0], right, sources, current[3] + (number,)
                )
                continue
            pieces.append(current)
        current = (left, right, sources, (number,))
    if current is not None:
        pieces.append(current)
    return tuple(
        RecoveredRange(
            left,
            right,
            RECOVERED if sources else PENDING,
            sources,
            blocks,
            None if sources else REASON_AMBIGUOUS,
        )
        for left, right, sources, blocks in pieces
    )


def _algorithms(declaration):
    return tuple(sorted({digest.algorithm for digest in declaration.digests}))


def _digests_are_block_local(declaration, blocksize, size):
    """Whether every digest covers exactly one whole block.

    Only then are block choices independent, so a search that hit its limit
    can still deliver the bytes that every option agrees on without guessing.
    """
    for digest in declaration.digests:
        end = size if digest.end is None else digest.end
        if digest.start % blocksize or end % blocksize:
            return False
        if end - digest.start != blocksize:
            return False
    return True


def _block_options(replicas, lengths, blocksize, resolved):
    """Collect, for each block, the distinct values allowed by block digests."""
    result = []
    for number, length in enumerate(lengths, start=1):
        options = {}
        for replica in replicas:
            block = replica.blocks.get(number)
            if block is None or len(block) != length:
                continue
            options.setdefault(block, []).append(replica.name)
        start = (number - 1) * blocksize
        for dstart, dend, digest in resolved:
            if dstart == start and dend == start + length:
                options = {
                    value: names
                    for value, names in options.items()
                    if digest.matches(value)
                }
        result.append(options)
    return result


def _block_local_result(name, replicas, declaration, lengths, blocksize,
                        options, algorithms):
    """Build a partial result when block digests make each block independent."""
    data = bytearray()
    blocks = []
    for number, (length, choices) in enumerate(
        zip(lengths, options), start=1
    ):
        start = (number - 1) * blocksize
        if len(choices) == 1:
            value, names = next(iter(choices.items()))
        elif choices:
            value, names = next(iter(choices.items()))
            names = ()
        else:
            value, names = b"\x00" * length, ()
        data.extend(value)
        blocks.append(
            BlockSource(
                block=number,
                start=start,
                end=start + length,
                length=length,
                sources=tuple(sorted(names)),
                is_last=number == len(lengths),
                is_short=0 < length < blocksize,
                is_empty=length == 0,
            )
        )
    data = bytes(data)
    ranges = []
    cursor = None
    for block in blocks:
        if block.sources:
            if cursor is not None and cursor[1] == block.start and cursor[2] == block.sources:
                cursor = (cursor[0], block.end, cursor[2], cursor[3] + (block.block,))
            else:
                if cursor is not None:
                    ranges.append(cursor)
                cursor = (block.start, block.end, block.sources, (block.block,))
        else:
            if cursor is not None:
                ranges.append(cursor)
                cursor = None
            ranges.append(
                (block.start, block.end, (), (block.block,))
            )
    if cursor is not None:
        ranges.append(cursor)
    recovered = tuple(
        RecoveredRange(start, end, RECOVERED, sources, blocks)
        for start, end, sources, blocks in ranges
        if sources
    )
    pending = tuple(
        RecoveredRange(start, end, PENDING, (), blocks, REASON_AMBIGUOUS)
        for start, end, sources, blocks in ranges
        if not sources
    )
    merged = tuple(
        sorted(
            (
                item
                for item in recovered + pending
                if item.start < item.end
            ),
            key=lambda item: item.start,
        )
    )
    return FileRecoveryResult(
        name=name,
        size=len(data),
        blocksize=blocksize,
        version=declaration.version,
        complete=False,
        empty=len(data) == 0,
        data=data,
        ranges=merged,
        blocks=tuple(blocks),
        segments=_segments_result(
            declaration, len(data), blocksize, (data,), replicas
        ),
        legal_completions=0,
        reason=REASON_LIMIT,
        size_inferred=True,
        algorithms=algorithms,
    )


def recover_file(
    replicas,
    declaration=None,
    name=None,
    digests=None,
    size=None,
    blocksize=None,
    version=None,
    algorithm=None,
    max_candidates=None,
    max_nodes=None,
):
    """Recover one file from incomplete receive replicas.

    ``replicas`` may be :class:`Replica` objects or mappings.  The declaration
    may be a :class:`VersionDeclaration`, a mapping, or supplied by keyword.
    Only block combinations that satisfy the size, block size, version tag,
    and every segment digest are accepted.

    If more than one complete file satisfies the declaration, only ranges that
    are identical across all of them are marked recovered; the rest are
    pending with reason ``ambiguous``.
    """
    if isinstance(replicas, FileReplicas):
        spec = replicas
        replicas = spec.replicas
        declaration = spec.declaration
        name = name or spec.name

    if declaration is not None and not isinstance(declaration, VersionDeclaration):
        declaration = VersionDeclaration.from_mapping(declaration)
    if declaration is None:
        declaration = VersionDeclaration()

    values = declaration.as_dict()
    values["max_candidates"] = declaration.max_candidates
    values["max_nodes"] = declaration.max_nodes
    if size is not None:
        values["size"] = size
    if blocksize is not None:
        values["blocksize"] = blocksize
    if version is not None:
        values["version"] = version
    if digests is not None:
        values["digests"] = digests
    if algorithm is not None:
        values["algorithm"] = algorithm
    if max_candidates is not None:
        values["max_candidates"] = max_candidates
    if max_nodes is not None:
        values["max_nodes"] = max_nodes
    declaration = VersionDeclaration.from_mapping(values)

    replicas = tuple(
        Replica.from_mapping(item, index=index)
        for index, item in enumerate(replicas)
    )
    if not replicas:
        raise RecoveryDeclarationError("at least one replica is required")

    replicas = _eligible_replicas(replicas, declaration)
    if not replicas:
        target = declaration.size
        return FileRecoveryResult(
            name=name or "",
            size=target,
            blocksize=declaration.blocksize,
            version=declaration.version,
            complete=False,
            empty=False,
            data=None,
            ranges=_pending_whole(target, REASON_MISSING),
            legal_completions=0,
            reason=REASON_MISSING,
            algorithms=tuple(
                sorted({item.algorithm for item in declaration.digests})
            ),
        )
    block_size = _infer_blocksize(replicas, declaration)
    algorithms = _algorithms(declaration)

    size_inferred = False
    if declaration.size is not None:
        layouts = [(declaration.size, False)]
    else:
        layouts = _eof_layouts(replicas, block_size)
        size_inferred = bool(layouts)
        if not layouts:
            return FileRecoveryResult(
                name=name or "",
                size=None,
                blocksize=block_size,
                version=declaration.version,
                complete=False,
                empty=False,
                data=None,
                ranges=_pending_whole(None, REASON_MISSING),
                legal_completions=0,
                reason=REASON_MISSING,
                eof_marker_missing=True,
                size_inferred=False,
                algorithms=algorithms,
            )

    candidates = []
    hit_limit = False
    missing_blocks = []
    for layout_size, _inferred in layouts:
        lengths = _block_lengths(layout_size, block_size)
        resolved = _resolve_digests(declaration, layout_size)
        search = _CandidateSearch(
            replicas,
            lengths,
            block_size,
            resolved,
            declaration.max_candidates,
            declaration.max_nodes,
        )
        found = search.run()
        if search.truncated:
            hit_limit = True
        missing_blocks.extend(search.missing)
        for content in found:
            if content not in candidates:
                candidates.append(content)

    sizes = {len(item) for item in candidates}
    chosen_size = sizes.pop() if len(sizes) == 1 else None

    if hit_limit:
        target = declaration.size if declaration.size is not None else chosen_size
        if target is not None and _digests_are_block_local(
            declaration, block_size, target
        ):
            lengths = _block_lengths(target, block_size)
            resolved = _resolve_digests(declaration, target)
            options = _block_options(
                replicas, lengths, block_size, resolved
            )
            return _block_local_result(
                name or "", replicas, declaration, lengths, block_size,
                options, algorithms,
            )
        return FileRecoveryResult(
            name=name or "",
            size=target,
            blocksize=block_size,
            version=declaration.version,
            complete=False,
            empty=False,
            data=None,
            ranges=_pending_whole(target, REASON_LIMIT),
            legal_completions=0,
            reason=REASON_LIMIT,
            size_inferred=size_inferred,
            algorithms=algorithms,
        )

    if not candidates:
        if missing_blocks:
            reason = REASON_MISSING
        else:
            reason = REASON_NO_COMPLETION
        target = declaration.size
        if target is None and layouts:
            target = layouts[0][0]
        return FileRecoveryResult(
            name=name or "",
            size=target,
            blocksize=block_size,
            version=declaration.version,
            complete=False,
            empty=False,
            data=None,
            ranges=_pending_whole(target, reason),
            legal_completions=0,
            reason=reason,
            size_inferred=size_inferred,
            algorithms=algorithms,
        )

    if chosen_size is None:
        target = declaration.size
        return FileRecoveryResult(
            name=name or "",
            size=target,
            blocksize=block_size,
            version=declaration.version,
            complete=False,
            empty=False,
            data=None,
            ranges=_pending_whole(target, REASON_AMBIGUOUS),
            legal_completions=len(candidates),
            reason=REASON_AMBIGUOUS,
            size_inferred=size_inferred,
            algorithms=algorithms,
        )

    total_size = chosen_size
    empty = total_size == 0
    unique = len(candidates) == 1

    if unique:
        data = candidates[0]
        lengths = _block_lengths(total_size, block_size)
        blocks = []
        for number, length in enumerate(lengths, start=1):
            start = (number - 1) * block_size
            end = start + length
            sources = tuple(
                replica.name
                for replica in replicas
                if _block_sources(replica, number, data, block_size)
            )
            blocks.append(
                BlockSource(
                    block=number,
                    start=start,
                    end=end,
                    length=length,
                    sources=sources,
                    is_last=number == len(lengths),
                    is_short=0 < length < block_size,
                    is_empty=length == 0,
                )
            )
        if empty:
            ranges = (
                RecoveredRange(0, 0, RECOVERED, blocks[0].sources, (1,), None),
            )
        else:
            ranges = _group_ranges(replicas, data, block_size, blocks)
        return FileRecoveryResult(
            name=name or "",
            size=total_size,
            blocksize=block_size,
            version=declaration.version,
            complete=True,
            empty=empty,
            data=data,
            ranges=ranges,
            blocks=tuple(blocks),
            segments=_segments_result(
                declaration, total_size, block_size, candidates, replicas
            ),
            legal_completions=1,
            reason=None,
            size_inferred=size_inferred,
            eof_marker_missing=False,
            algorithms=algorithms,
        )

    representative = candidates[0]
    identical = _common_ranges(candidates)
    ranges = []
    cursor = 0
    for start, end in identical:
        sources, blocks = _sources_and_blocks(
            replicas, representative, block_size, start, end
        )
        if start > cursor:
            ranges.append(
                RecoveredRange(cursor, start, PENDING, (), (), REASON_AMBIGUOUS)
            )
        ranges.append(
            RecoveredRange(start, end, RECOVERED, sources, blocks)
        )
        cursor = end
    if cursor < total_size:
        ranges.append(
            RecoveredRange(cursor, total_size, PENDING, (), (), REASON_AMBIGUOUS)
        )

    lengths = _block_lengths(total_size, block_size)
    blocks = []
    for number, length in enumerate(lengths, start=1):
        start = (number - 1) * block_size
        end = start + length
        if all(
            item[start:end] == representative[start:end] for item in candidates
        ):
            sources = tuple(
                replica.name
                for replica in replicas
                if _block_sources(replica, number, representative, block_size)
            )
        else:
            sources = ()
        blocks.append(
            BlockSource(
                block=number,
                start=start,
                end=end,
                length=length,
                sources=sources,
                is_last=number == len(lengths),
                is_short=0 < length < block_size,
                is_empty=length == 0,
            )
        )

    return FileRecoveryResult(
        name=name or "",
        size=total_size,
        blocksize=block_size,
        version=declaration.version,
        complete=False,
        empty=False,
        data=representative,
        ranges=tuple(ranges),
        blocks=tuple(blocks),
        segments=_segments_result(
            declaration, total_size, block_size, candidates, replicas
        ),
        legal_completions=len(candidates),
        reason=REASON_AMBIGUOUS,
        size_inferred=size_inferred,
        eof_marker_missing=False,
        algorithms=algorithms,
    )


recover = recover_file
restore = recover_file
recover_segments = recover_file


def recover_batch(files, **kwargs):
    """Recover every file in a batch.

    ``files`` is an iterable of :class:`FileReplicas` objects or mappings.
    """
    results = []
    for item in files:
        spec = FileReplicas.from_mapping(item)
        results.append(recover_file(spec, **kwargs))
    return BatchRecoveryResult(tuple(results))


recover_files = recover_batch
recover_all = recover_batch


def write_plan(result, path):
    """Write a recovery plan as JSON."""
    with open(path, "w", encoding="utf-8") as handle:
        json.dump(result.as_dict(), handle, ensure_ascii=False, indent=2)
        handle.write("\n")
    return path


def main(argv=None):
    """Read a JSON manifest and print or write a recovery plan."""
    parser = argparse.ArgumentParser(
        prog="tftpy-recover",
        description="Recover files from incomplete TFTP receive replicas.",
    )
    parser.add_argument("manifest", help="JSON manifest of replicas and digests")
    parser.add_argument("-o", "--output-dir", default=None)
    parser.add_argument("--json", action="store_true", help="emit JSON")
    parser.add_argument(
        "--skip-incomplete",
        action="store_true",
        help="write complete files and leave incomplete ones pending",
    )
    options = parser.parse_args(argv)

    with open(options.manifest, "r", encoding="utf-8") as handle:
        payload = json.load(handle)
    if isinstance(payload, list):
        files = payload
    else:
        files = payload.get("files", [payload])
    result = recover_batch(files)

    if options.output_dir:
        result.write_all(
            options.output_dir, skip_incomplete=options.skip_incomplete
        )
    if options.json:
        print(json.dumps(result.as_dict(), ensure_ascii=False, indent=2))
    else:
        for item in result.files:
            if item.complete:
                print(
                    "%s: complete (%d bytes, eof source: %s)"
                    % (
                        item.name,
                        len(item.data or b""),
                        ", ".join(item.eof_source or item.empty_sources) or "-",
                    )
                )
            else:
                print(
                    "%s: pending (%s, %d range(s))"
                    % (item.name, item.reason, len(item.pending_ranges))
                )
    return 0 if result.complete else 1


